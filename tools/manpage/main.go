// Command manpage 生成 fast-https(1) 的 roff 手册页，中英各一份。
//
// 命令树直接取自 cmd.RootCmdForLang()，新增或改名子命令后重新生成即可，
// 不需要手抄一遍。FILES 与 EXAMPLES 是安装包布局相关的固定内容，
// 随打包方式变化时手工维护（两种语言各一张表）。
//
// 用法：
//
//	go run ./tools/manpage
//	go run ./tools/manpage -out build/packaging/man/fast-https.1 -out-en build/packaging/man/fast-https.en.1
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"fast-https/cmd"
	"fast-https/config"
)

const (
	defaultOut   = "build/packaging/man/fast-https.1"
	defaultEnOut = "build/packaging/man/fast-https.en.1"
)

func main() {
	out := flag.String("out", defaultOut, "中文手册页输出路径")
	outEn := flag.String("out-en", defaultEnOut, "英文手册页输出路径")
	flag.Parse()

	for _, item := range []struct {
		path string
		lang cmd.Lang
	}{
		{*out, cmd.LangZH},
		{*outEn, cmd.LangEN},
	} {
		if err := write(item.path, item.lang); err != nil {
			fmt.Fprintf(os.Stderr, "manpage: %v\n", err)
			os.Exit(1)
		}
	}
}

// write 生成一份手册页。两份文件内容只差说明文字，结构完全一致。
func write(path string, lang cmd.Lang) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("创建目录失败: %w", err)
	}
	page := Render(lang, config.CURRENT_VERSION)
	if err := os.WriteFile(path, []byte(page), 0o644); err != nil {
		return fmt.Errorf("写入 %s 失败: %w", path, err)
	}
	return nil
}

// usageLine 是 NAME 段的一句话说明。
func usageLine(lang cmd.Lang) string {
	if lang == cmd.LangEN {
		return "high performance web server and reverse proxy"
	}
	return "高性能 Web 服务器与反向代理"
}

