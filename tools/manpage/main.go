// Command manpage 生成 fast-https(1) 的 roff 手册页。
//
// 命令树直接取自 cmd.RootCmd()，新增或改名子命令后重新生成即可，不需要手抄一遍。
// FILES 与 EXAMPLES 是安装包布局相关的固定内容，随打包方式变化时手工维护。
//
// 用法：
//
//	go run ./tools/manpage
//	go run ./tools/manpage -out build/packaging/man/fast-https.1
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"fast-https/cmd"
	"fast-https/config"
)

const defaultOut = "build/packaging/man/fast-https.1"

func main() {
	out := flag.String("out", defaultOut, "输出 roff 文件")
	flag.Parse()

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "manpage: 创建目录失败: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(Render(cmd.RootCmd(), config.CURRENT_VERSION)), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "manpage: 写入 %s 失败: %v\n", *out, err)
		os.Exit(1)
	}
}

// files 是发行版包安装后的路径约定，与 config/base_dir_rpm.go 的
// FAST_HTTPS_BASE_DIR（/usr/share/fast-https/）保持一致。
var files = [][2]string{
	{"/usr/share/fast-https/config/fast-https.json", "main configuration file"},
	{"/usr/share/fast-https/config/mime.json", "MIME type table"},
	{"/usr/share/fast-https/config/conf.d/", "extra server definitions referenced by http.include"},
	{"/usr/share/fast-https/config/cert/", "certificate and key files"},
	{"/usr/share/fast-https/httpdoc/root/", "default site root"},
	{"/usr/share/fast-https/logs/", "log output directory"},
	{"/usr/lib/systemd/system/fast-https.service", "systemd unit"},
	{"/usr/share/doc/fast-https/usage.html", "full usage document"},
}

// Render 把命令树渲染成 roff。输出不含日期，保证同一份命令定义总是生成同样的字节。
func Render(root *cobra.Command, version string) string {
	var b strings.Builder

	b.WriteString(".\\\" generated by tools/manpage, do not edit\n")
	ver := strings.TrimPrefix(escape(version), "V")
	fmt.Fprintf(&b, ".TH FAST\\-HTTPS 1 \"\" \"fast\\-https %s\" \"User Commands\"\n", ver)

	b.WriteString(".SH NAME\n")
	b.WriteString("fast\\-https \\- high performance web server and reverse proxy\n")

	b.WriteString(".SH SYNOPSIS\n")
	b.WriteString(".B fast\\-https\n")
	b.WriteString("[\\fICOMMAND\\fR]\n")

	b.WriteString(".SH DESCRIPTION\n")
	writeParagraphs(&b, root.Long)

	b.WriteString(".SH COMMANDS\n")
	for _, sub := range subcommands(root) {
		b.WriteString(".TP\n")
		fmt.Fprintf(&b, ".B %s\n", escape(sub.Name()))
		b.WriteString(escape(sub.Short) + "\n")
	}

	b.WriteString(".SH FILES\n")
	for _, f := range files {
		b.WriteString(".TP\n")
		fmt.Fprintf(&b, ".I %s\n", escape(f[0]))
		b.WriteString(escape(f[1]) + "\n")
	}

	b.WriteString(".SH EXAMPLES\n")
	examples := [][2]string{
		{"fast-https start", "start the server; systemd and containers keep it in the foreground"},
		{"fast-https status", "print whether the server is running"},
		{"fast-https reload", "reload configuration without dropping connections"},
		{"fast-https stop", "stop the server and wait for in-flight requests"},
		{"fast-https check", "validate the configuration without listening"},
	}
	for _, e := range examples {
		b.WriteString(".TP\n")
		fmt.Fprintf(&b, ".B %s\n", escape(e[0]))
		b.WriteString(escape(e[1]) + "\n")
	}

	b.WriteString(".SH SEE ALSO\n")
	b.WriteString("systemctl(1), fast\\-https.service(5)\n")

	return b.String()
}

// subcommands 返回可展示的子命令，按名称排序保证输出稳定。
func subcommands(root *cobra.Command) []*cobra.Command {
	var subs []*cobra.Command
	for _, c := range root.Commands() {
		if !c.IsAvailableCommand() || c.IsAdditionalHelpTopicCommand() {
			continue
		}
		subs = append(subs, c)
	}
	sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
	return subs
}

// writeParagraphs 把空行分隔的说明拆成 roff 段落，段间用 .PP 分隔。
func writeParagraphs(b *strings.Builder, text string) {
	var paras []string
	for _, p := range strings.Split(strings.TrimSpace(text), "\n\n") {
		if p = strings.TrimSpace(p); p != "" {
			paras = append(paras, escape(strings.Join(strings.Fields(p), " ")))
		}
	}
	b.WriteString(strings.Join(paras, "\n.PP\n") + "\n")
}

// escape 处理 roff 里有特殊含义的字符：反斜杠、行首的点和单引号。
func escape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, "-", `\-`)
	if strings.HasPrefix(s, ".") || strings.HasPrefix(s, "'") {
		s = `\&` + s
	}
	return s
}
